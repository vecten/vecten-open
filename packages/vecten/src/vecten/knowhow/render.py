"""Every copy of the package skills: the project's, the plugin's and the guide document in docs/."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from vecten.knowhow import ENTRY_SKILL, SKILL_FILE, load_skill, skill_body, skill_names
from vecten.knowhow.mcp_servers import mcp_servers_document
from vecten_shared.config import load_config
from vecten_shared.records import write_text_atomic
from vecten_shared.versions import VERSIONS

PLUGIN_DIR = Path("plugins") / "vecten"
PUBLIC_URL = "https://github.com/vecten/vecten-open"
MARKETPLACE_FILE = Path(".claude-plugin") / "marketplace.json"
MCP_JSON = ".mcp.json"
GUIDE_DOCUMENT = Path("docs") / "agent-guide.md"
GUIDE_PREAMBLE = (
    "<!-- Generated by `vecten dev render-plugin` from the package's guide skill\n"
    "     (knowhow/skills/guide/SKILL.md). Edit the skill and re-render; never this file. -->\n"
)


def _describe(names: list[str]) -> str:
    listed = names[0] if len(names) == 1 else f"{', '.join(names[:-1])} and {names[-1]}"
    return f"The vecten skills: {listed}."


PLUGIN_DESCRIPTION = _describe(skill_names())


def _json_text(doc: object) -> str:
    return json.dumps(doc, indent=2) + "\n"


def mcp_json_text() -> str:
    return _json_text(mcp_servers_document())


def plugin_manifest_text() -> str:
    return _json_text(
        {
            "name": "vecten",
            "description": PLUGIN_DESCRIPTION,
            "version": VERSIONS.vecten,
            "author": {"name": "Vecten"},
            "homepage": PUBLIC_URL,
            "repository": PUBLIC_URL,
            "license": "Apache-2.0",
        }
    )


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    write_text_atomic(path, text)


def marketplace_text() -> str:
    return _json_text(
        {
            "name": "vecten",
            "owner": {"name": "Vecten"},
            "plugins": [
                {
                    "name": "vecten",
                    "source": f"./{PLUGIN_DIR.as_posix()}",
                    "description": PLUGIN_DESCRIPTION,
                    "version": VERSIONS.vecten,
                    "homepage": PUBLIC_URL,
                    "repository": PUBLIC_URL,
                }
            ],
        }
    )


def vendor_skills(target: Path) -> list[Path]:
    # The evals beside each skill are package test material, so the project gets the text only.
    written = []
    for name in skill_names():
        path = target / "skills" / name / SKILL_FILE
        _write(path, load_skill(name))
        written.append(path)
    # Both servers read Airflow or the dbt project, which only the platform component has.
    if load_config(target).has("platform"):
        mcp = target / MCP_JSON
        _write(mcp, mcp_json_text())
        written.append(mcp)
    return written


def _plugin_files(repo_root: Path) -> dict[Path, str]:
    # The plugin carries skills only: MCP servers declared in a plugin start in every session
    # of every project, so the servers come with the rendered project instead.
    plugin = repo_root / PLUGIN_DIR
    files = {
        repo_root / MARKETPLACE_FILE: marketplace_text(),
        plugin / ".claude-plugin" / "plugin.json": plugin_manifest_text(),
    }
    for name in skill_names():
        files[plugin / "skills" / name / SKILL_FILE] = load_skill(name)
    return files


def _stale_skill_entries(plugin: Path) -> list[Path]:
    # A skill renamed or dropped in the package must not survive in the plugin under its old name.
    root = plugin / "skills"
    if not root.is_dir():
        return []
    names = set(skill_names())
    stale = []
    # Dotfiles such as `.DS_Store` are the file manager's, never a rendered skill.
    for entry in sorted(e for e in root.iterdir() if not e.name.startswith(".")):
        if entry.name not in names or not entry.is_dir():
            stale.append(entry)
            continue
        stale += [
            p
            for p in sorted(entry.iterdir())
            if p.name != SKILL_FILE and not p.name.startswith(".")
        ]
    return stale


def render_plugin(repo_root: Path, *, check: bool = False) -> list[Path]:
    """Write the plugin and the marketplace file; return what differed. `check` writes nothing."""
    plugin = repo_root / PLUGIN_DIR
    changed = []
    for path, text in _plugin_files(repo_root).items():
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        changed.append(path)
        if not check:
            _write(path, text)
    for path in _stale_skill_entries(plugin):
        changed.append(path)
        if not check:
            if path.is_dir():
                shutil.rmtree(path)
            else:
                path.unlink()
    return changed


def guide_document() -> str:
    return GUIDE_PREAMBLE + "\n" + skill_body(ENTRY_SKILL)


def render_guide_document(repo_root: Path, *, check: bool = False) -> bool:
    """Write the guide skill's body to docs/; return whether it was absent or differed."""
    path = repo_root / GUIDE_DOCUMENT
    text = guide_document()
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    if not check:
        _write(path, text)
    return True
